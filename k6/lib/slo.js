/**
 * SLO — 측정을 시작하기 전에 선언하는 품질 기준.
 *
 * ── 이 파일을 다루는 규칙 ────────────────────────────────────
 * 이 값은 "미리 정한 한계"의 단일 출처다.
 * 측정 결과가 기준을 못 지킨다고 해서 이 값을 낮추면,
 * 실험이 검증에서 사후 정당화로 바뀐다.
 *
 * 값을 바꾸려면:
 *   1. 아래 근거 주석을 먼저 고치고
 *   2. 이전에 측정한 결과는 전부 폐기한다 (기준이 다르면 비교 불가)
 *   3. 변경을 커밋 메시지에 남긴다
 *
 * ── 변경 이력 ────────────────────────────────────────────────
 * 2026-08-08 기준 강화. WRITE 300→200ms, ERROR 1%→0.1%, p99·CHECK_RATE 추가.
 *   개선 라운드를 여러 번 돌 계획이므로 기준을 느슨하게 잡으면
 *   초반 병목이 기준에 가려져 "이미 통과"로 보인다.
 *   이 변경 이전에 측정한 결과(2026-08-08 markers-r10, mixed-r30)는 폐기한다.
 *
 * ── 근거 ────────────────────────────────────────────────────
 * READ p95 100ms / p99 200ms
 *   지도 상세 화면 하나가 마커 조회와 추억 목록 두 API를 호출한다.
 *   사용자가 "즉시 반응했다"고 느끼는 구간이 100ms 이하이고,
 *   API 두 개가 순차로 걸려도 200ms 안에 끝나 체감 지연이 없다.
 *
 * WRITE p95 200ms / p99 400ms
 *   사용자가 저장 버튼을 누르고 기다리는 맥락이라 read보다 관대해도 된다.
 *   다만 텍스트 추억 생성은 INSERT 한 건 + 권한 확인이 전부인 가벼운
 *   트랜잭션이므로 300ms는 병목을 가릴 만큼 후하다. 200ms로 조인다.
 *
 * UPLOAD p95 200ms / p99 400ms
 *   요청에 파일 전송과 S3 왕복이 포함된다. (JPEG 1MB x3 + MP3 3MB = 약 6MB)
 *   진행률 UI가 있어 사용자가 대기를 예상하는 상황이므로 가장 관대하다.
 *
 * p99를 함께 거는 이유
 *   p95만 걸면 상위 5% 요청이 폭주해도 통과한다. 커넥션 풀 대기나
 *   GC pause 같은 간헐 병목은 p99에서 먼저 드러난다.
 *   꼬리(p99)가 몸통(p95)의 2배를 넘으면 병목이 있다고 본다.
 *
 * ERROR_RATE 0.1%
 *   부하 테스트에서 오류는 "느려짐"이 아니라 "깨짐"이다.
 *   1%는 3분 측정(수만 건)에서 수백 건의 실패를 허용해 버린다.
 *   1,000건 중 1건까지만 용인한다.
 *
 * CHECK_RATE 99.5%
 *   check는 상태 코드가 기대값인지 본다. http_req_failed(4xx 제외)가
 *   놓치는 실패(200이지만 빈 응답 등)를 잡는 이중 안전망이다.
 *
 * ── 주의 ────────────────────────────────────────────────────
 * 여기 없는 것: "동시 사용자 N명"
 * 용량은 미리 정하는 값이 아니라 측정해서 나오는 결과다.
 * 이 SLO를 지키면서 견디는 최대 부하가 곧 그 시점의 용량이다.
 */
export const SLO = {
  READ_P95_MS: 100,
  READ_P99_MS: 200,
  WRITE_P95_MS: 200,
  WRITE_P99_MS: 400,
  UPLOAD_P95_MS: 200,
  UPLOAD_P99_MS: 400,
  ERROR_RATE: 0.001,
  CHECK_RATE: 0.995,
};

